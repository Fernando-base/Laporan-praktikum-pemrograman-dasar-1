round = 5
distance = 14

around = distance / round
radius = around / float(2 * 3.14)


print("Diketahui :")
print(f"Pak Dengklek mengelilingi taman = {round} putaran")
print(f"Jarak tempuh Pak Dengklek = {distance} Kilometer\n")
print("Jawaban :")
print(f"Jari-jari taman yang dikelilingi Pak Dengklek adalah{radius : .2f} Kilometer")